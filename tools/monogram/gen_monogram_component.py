import re, pathlib, json

svg = pathlib.Path('public/art/monogram.svg').read_text()
transform = re.search(r'<g transform="([^"]+)"', svg).group(1)
paths = re.findall(r'<path d="(.*?)"', svg, re.S)
paths = [' '.join(p.split()) for p in paths]

# Guide centrelines: stroke order and direction authored by hand (no tracer can
# infer how a hand would write the mark), geometry then snapped onto the real
# skeleton by tools/monogram/snap_guides.py. Eyeballed curves drifted off the ink —
# the script L measured a median half-width of 0, i.e. off its own stroke for
# half its length, which is why the reveal left so much to fill.
GUIDES = [(g["name"], g["d"]) for g in json.load(open("tools/monogram/guides.json"))]

ink = "\n".join(f'      <path d="{p}" />' for p in paths)
guides = "\n".join(
    f'        <path ref={{registerGuide}} data-name="{n}" d="{d}" />' for n, d in GUIDES
)

tsx = f'''import {{ useCallback, useEffect, useId, useRef, useState, useSyncExternalStore }} from "react";

/**
 * The LL monogram, drawn the way it was written.
 *
 * The outline is a potrace trace of the save-the-date artwork, so the letterform
 * keeps the real variable-width watercolour edges. The reveal works by masking
 * that outline with a thick stroke animated along hand-authored centrelines in
 * writing order — a centreline *stroke* would flatten the mark to a uniform
 * width, and no tracing algorithm can infer stroke order anyway.
 *
 * The mask is dropped once the animation finishes: the guides do not cover every
 * last sliver of ink (notably the tail of the swash), so the final frame must be
 * the untouched artwork rather than whatever the mask happened to reach.
 *
 * Generated by tools/monogram/gen_monogram_component.py — see that folder's
 * README. Edit the guides there and regenerate; do not edit this file.
 */

const DRAW_MS = 2400;
const SETTLE_MS = 200;

const REDUCED_QUERY = "(prefers-reduced-motion: reduce)";

function subscribeReducedMotion(onChange: () => void) {{
  const mq = window.matchMedia(REDUCED_QUERY);
  mq.addEventListener("change", onChange);
  return () => mq.removeEventListener("change", onChange);
}}

/**
 * useSyncExternalStore rather than an effect: this decides what renders on the
 * very first paint, and reading it in an effect would mean drawing the mask and
 * then tearing it down for someone who asked not to see motion.
 * The server snapshot is `true` — no motion until we know otherwise.
 */
function usePrefersReducedMotion() {{
  return useSyncExternalStore(
    subscribeReducedMotion,
    () => window.matchMedia(REDUCED_QUERY).matches,
    () => true,
  );
}}

export function Monogram({{
  className,
  title = "Laura and Lucien",
  animate = true,
}}: {{
  className?: string;
  title?: string;
  animate?: boolean;
}}) {{
  const guidesRef = useRef<SVGPathElement[]>([]);
  const [settled, setSettled] = useState(false);
  const reduced = usePrefersReducedMotion();
  // useId, not a random string: a random mask id differs between the server and
  // client renders and breaks hydration.
  const maskId = `mono-${{useId().replace(/:/g, "")}}`;
  const masked = animate && !reduced;

  const registerGuide = useCallback((el: SVGPathElement | null) => {{
    if (el && !guidesRef.current.includes(el)) guidesRef.current.push(el);
  }}, []);

  useEffect(() => {{
    if (!masked) return;

    const guides = guidesRef.current;
    const lengths = guides.map((g) => g.getTotalLength());
    const total = lengths.reduce((a, b) => a + b, 0);
    if (!total) return;

    guides.forEach((g, i) => {{
      g.style.strokeDasharray = String(lengths[i]);
      g.style.strokeDashoffset = String(lengths[i]);
    }});

    let raf = 0;
    let start: number | null = null;

    const tick = (ts: number) => {{
      start ??= ts;
      const p = Math.min(1, (ts - start) / DRAW_MS);
      // decelerate, like a hand easing off at the end of a stroke
      let remaining = (1 - (1 - p) ** 2) * total;
      guides.forEach((g, i) => {{
        const take = Math.max(0, Math.min(lengths[i], remaining));
        g.style.strokeDashoffset = String(lengths[i] - take);
        remaining -= lengths[i];
      }});
      if (p < 1) raf = requestAnimationFrame(tick);
      else setSettled(true);
    }};

    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }}, [masked]);

  return (
    <svg
      viewBox="0 0 573 580"
      className={{className}}
      role="img"
      aria-label={{title}}
      xmlns="http://www.w3.org/2000/svg"
    >
      {{masked && (
        <defs>
          <mask id={{maskId}}>
            <g
              fill="none"
              stroke="#fff"
              strokeWidth={{56}}
              strokeLinecap="round"
              strokeLinejoin="round"
            >
{guides}
            </g>
          </mask>
        </defs>
      )}}
      {{/* The mask must sit on an untransformed wrapper: mask content resolves in
          the referencing element's user space, and the inner group carries
          potrace's flipped scale(0.1,-0.1). */}}
      <g mask={{masked ? `url(#${{maskId}})` : undefined}}>
        <g transform="{transform}" fill="currentColor">
{ink}
        </g>
      </g>

      {{/* The guides are centrelines, so a finite stroke never quite covers the
          widest parts of the ink — most visibly the tail of the swash. Removing
          the mask on completion made the whole mark snap to full weight in one
          frame. This unmasked copy fades in over the top instead, so what the
          stroke missed arrives as a settle rather than a pop. */}}
      {{masked && (
        <g
          style={{{{
            opacity: settled ? 1 : 0,
            transition: `opacity ${{SETTLE_MS}}ms ease-out`,
          }}}}
        >
          <g transform="{transform}" fill="currentColor">
{ink}
          </g>
        </g>
      )}}
    </svg>
  );
}}
'''

out = pathlib.Path('src/components/wedding/monogram.tsx')
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(tsx)
print(f'wrote {out} ({len(tsx)} bytes, {len(paths)} ink paths, {len(GUIDES)} guides)')
